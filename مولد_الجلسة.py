def الحصول_على_بيانات_api():
    """الحصول على بيانات API من المستخدم"""
    print("\n📱 خطوة 1: أدخل بيانات API الخاصة بك")
    print("   (يمكنك الحصول عليها من: https://my.telegram.org/apps)")
    print("   " + "─" * 50 + "\n")
    
    while True:
        try:
            معرف_api = int(input("🔑 معرف API (API ID): ").strip())
            break
        except ValueError:
            print("❌ خطأ: معرف API يجب أن يكون أرقاماً فقط! حاول مرة أخرى.\n")
    
    هاش_api = input("🔐 هاش API (API HASH): ").strip()
    return معرف_api, هاش_api

def الحصول_على_رقم_الهاتف():
    """الحصول على رقم الهاتف مع رمز الدولة"""
    print("\n📱 خطوة 2: أدخل رقم هاتفك")
    print("   " + "─" * 50)
    print("   ⚠️  تأكد من كتابة رمز الدولة (مثال: +966512345678)")
    print("   أو (مثال: 00966512345678)\n")
    
    رقم_الهاتف = input("📞 رقم الهاتف: ").strip()
    return رقم_الهاتف

def توليد_الجلسة(معرف_api, هاش_api, رقم_الهاتف):
    """توليد Session String الجلسة"""
    try:
        print("\n🔄 جاري الاتصال بخوادم تليجرام...")
        print("⏳ يرجى الانتظار...\n")
        
        with Client(
            name="مولد_الجلسة",
            api_id=معرف_api,
            api_hash=هاش_api,
            in_memory=True
        ) as التطبيق:
            print("✅ تم الاتصال بنجاح!\n")
            
            # هنا سيطلب كود التحقق تلقائياً
            print("📨 تم إرسال رمز التحقق إلى تطبيق تليجرام")
            print("🔢 أدخل الرمز المكون من 5 أرقام\n")
            
            نص_الجلسة = التطبيق.export_session_string()
            
            print("\n" + "═" * 60)
            print("🎉 تم إنشاء الجلسة بنجاح!")
            print("═" * 60)
            print("\n📋 نص الجلسة الخاص بك (انسخه بالكامل):")
            print("─" * 60)
            print(nص_الجلسة)
            print("─" * 60)
            
            print("\n⚠️  تحذير أمني مهم:")
            print("   • لا تشارك هذا النص مع أي شخص")
            print("   • هذا النص يسمح بالوصول الكامل لحسابك")
            print("   • احتفظ به في مكان آمن")
            
            return نص_الجلسة
            
    except ApiIdInvalid:
        print("\n❌ خطأ: معرف API أو هاش API غير صحيح!")
        print("   تأكد من نسخ البيانات بشكل صحيح من my.telegram.org")
        return None
        
    except PhoneNumberInvalid:
        print("\n❌ خطأ: رقم الهاتف غير صحيح!")
        print("   تأكد من كتابة رمز الدولة بشكل صحيح")
        print("   مثال: +966512345678 أو 00966512345678")
        return None
        
    except FloodWait as انتظار:
        print(f"\n⏳ خطأ: عدد المحاولات كبير جداً!")
        print(f"   يرجى الانتظار {انتظار.value} ثانية قبل المحاولة مرة أخرى")
        time.sleep(انتظار.value)
        return None
        
    except Exception as خطأ:
        print(f"\n❌ خطأ غير متوقع: {خطأ}")
        print("   يرجى المحاولة مرة أخرى")
        return None

